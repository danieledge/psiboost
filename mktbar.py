def page_free():
    """The Psion and its lead as in PageAlways, the lead going up to a plug
    that is not in anything (Free the serial port)."""
    art = dict(PICTURES)['PageAlways']
    rows, w, h = parse(art)
    rows = [list(r) for r in rows]
    for y in range(4, 34):                   # the modem's box and its lead, gone
        for x in range(35, 64):
            rows[y][x] = '.'
    plug = [
        "kkkkkkkkkkkkkkkkkk",
        "kwwwwwwwwwwwwwwwwk",
        "kwkwwkwwkwwkwwkwwk",
        "kwwwwwwwwwwwwwwwwk",
        ".kwwkwwkwwkwwkwwk.",
        ".kwwwwwwwwwwwwwwk.",
        "..kkkkkkkkkkkkkk..",
        "...kddddddddddk...",
        "...kddddddddddk...",
        "...kddddddddddk...",
        "....kkkkkkkkkk....",
    ]
    top, left = 9, 42
    for dy, line in enumerate(plug):
        for dx, c in enumerate(line):
            if c != '.':
                rows[top + dy][left + dx] = c
    for y in range(top + len(plug), 34):     # the lead, down to the Psion's
        rows[y][51] = 'k'
    for x in range(34, 52):
        rows[33][x] = 'k'
    return '\n' + '\n'.join(''.join(r) for r in rows) + '\n'


def parse(art):
    rows = [r for r in art.strip('\n').split('\n')]
    w = max(len(r) for r in rows)
    rows = [r.ljust(w, '.') for r in rows]
    return rows, w, len(rows)


def main():
    out, header = sys.argv[1], sys.argv[2]
    os.makedirs(out, exist_ok=True)
    files, ids = [], []
    pictures = list(PICTURES)
    pictures.insert(1, ('PageFree', page_free()))
    for name, art in ICONS + pictures:
        rows, w, h = parse(art)
        if name.startswith('Page'):
            if (w, h) != (64, 48):
                raise SystemExit(f'{name}: {w}x{h}, the page\'s pictures are 64x48')
        elif h != 20 or not 16 <= w <= 24:
            raise SystemExit(f'{name}: {w}x{h}, toolbar pictures are 24x20 (or narrower)')
        img = Image.new('L', (w, h), 255)
        mask = Image.new('1', (w, h), 1)
        for y, r in enumerate(rows):
            for x, c in enumerate(r):
                if c not in GREY:
                    raise SystemExit(f'{name}: bad pixel {c!r}')
                img.putpixel((x, y), GREY[c])
                if c != '.':
                    mask.putpixel((x, y), 0)
        fi = os.path.join(out, f'{name}.bmp')
        fm = os.path.join(out, f'{name}_m.bmp')
        img.convert('RGB').save(fi)
        mask.convert('RGB').save(fm)
        files += [fi, fm]
        ids.append(name)
    text = '/* spicons.h - made by mktbar.py: PsiBoost.mbm ids */\n'
    text += '#ifndef SPICONS_H\n#define SPICONS_H\nenum TSpIconId\n\t{\n'
    for i, n in enumerate(ids):
        text += f'\tEMbm{n} = {2 * i}, EMbm{n}Mask = {2 * i + 1},\n'
    text += f'\tEMbmCount = {2 * len(ids)}\n\t}};\n#endif\n'
    old = open(header).read() if os.path.exists(header) else ''
    if old != text:
        with open(header, 'w') as f:
            f.write(text)
    with open(os.path.join(out, 'files.txt'), 'w') as f:
        for i, p in enumerate(files):
            f.write(('/2' if i % 2 == 0 else '/1') + os.path.basename(p) + '\n')


if __name__ == '__main__':
    main()
